CREATE TABLE public.material_requests (
	id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
	date timestamp with time zone NOT NULL DEFAULT now(),
	construction_site_id integer NOT NULL REFERENCES public.construction_sites(id) ON DELETE RESTRICT ON UPDATE CASCADE,
	construction_manager_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
	comment text,
	version bigint NOT NULL DEFAULT 1,
	CHECK (version > 0)
);

COMMENT ON TABLE public.material_requests IS 'Material request document headers.';
COMMENT ON COLUMN public.material_requests.date IS 'Document date and time.';
COMMENT ON COLUMN public.material_requests.construction_site_id IS 'Construction site requesting the materials.';
COMMENT ON COLUMN public.material_requests.construction_manager_id IS 'Manager responsible for the material request.';
COMMENT ON COLUMN public.material_requests.comment IS 'Optional document comment.';
COMMENT ON COLUMN public.material_requests.version IS 'Optimistic concurrency version.';

CREATE INDEX material_requests_construction_site_id_idx
	ON public.material_requests USING btree (construction_site_id);

CREATE INDEX material_requests_construction_manager_id_idx
	ON public.material_requests USING btree (construction_manager_id);

CREATE INDEX material_requests_date_idx
	ON public.material_requests USING btree (date);

CREATE TABLE public.material_request_items (
	id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
	line_num integer NOT NULL,
	material_request_id integer NOT NULL REFERENCES public.material_requests(id) ON DELETE CASCADE ON UPDATE CASCADE,
	material_id integer NOT NULL REFERENCES public.materials(id) ON DELETE RESTRICT ON UPDATE CASCADE,
	measure_unit_id integer NOT NULL REFERENCES public.measure_units(id) ON DELETE RESTRICT ON UPDATE CASCADE,
	quant numeric(19, 4) NOT NULL,
	supplier_id integer REFERENCES public.suppliers(id) ON DELETE RESTRICT ON UPDATE CASCADE,
	required_date date,
	order_importance_id integer NOT NULL REFERENCES public.order_importances(id) ON DELETE RESTRICT ON UPDATE CASCADE,
	status_id integer NOT NULL DEFAULT 1 REFERENCES public.material_request_statuses(id) ON DELETE RESTRICT ON UPDATE CASCADE,
	CHECK (line_num > 0),
	CHECK (quant > 0)
);

COMMENT ON TABLE public.material_request_items IS 'Material request document lines.';
COMMENT ON COLUMN public.material_request_items.line_num IS 'Line number within the document.';
COMMENT ON COLUMN public.material_request_items.material_request_id IS 'Parent material request document.';
COMMENT ON COLUMN public.material_request_items.material_id IS 'Requested material.';
COMMENT ON COLUMN public.material_request_items.measure_unit_id IS 'Measurement unit copied from the selected material.';
COMMENT ON COLUMN public.material_request_items.quant IS 'Requested quantity.';
COMMENT ON COLUMN public.material_request_items.supplier_id IS 'Optional supplier assigned by a supply user.';
COMMENT ON COLUMN public.material_request_items.required_date IS 'Optional date by which the material is required.';
COMMENT ON COLUMN public.material_request_items.order_importance_id IS 'Request importance level.';
COMMENT ON COLUMN public.material_request_items.status_id IS 'Request item workflow status; new lines start in draft status.';

CREATE UNIQUE INDEX material_request_items_request_line_idx
	ON public.material_request_items USING btree (material_request_id, line_num);

CREATE INDEX material_request_items_material_id_idx
	ON public.material_request_items USING btree (material_id);

CREATE INDEX material_request_items_supplier_id_idx
	ON public.material_request_items USING btree (supplier_id);

CREATE INDEX material_request_items_importance_id_idx
	ON public.material_request_items USING btree (order_importance_id);

CREATE INDEX material_request_items_status_id_idx
	ON public.material_request_items USING btree (status_id);

CREATE INDEX material_request_items_required_date_idx
	ON public.material_request_items USING btree (required_date);

CREATE OR REPLACE FUNCTION public.order_importances_ref(public.order_importances)
RETURNS json AS
$function$
	SELECT CASE WHEN $1.id IS NULL THEN NULL ELSE json_build_object(
		'keys', json_build_object('id', $1.id),
		'descr', $1.name,
		'dataType', 'orderImportances'
	) END;
$function$
LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION public.material_request_statuses_ref(public.material_request_statuses)
RETURNS json AS
$function$
	SELECT CASE WHEN $1.id IS NULL THEN NULL ELSE json_build_object(
		'keys', json_build_object('id', $1.id),
		'descr', $1.name,
		'dataType', 'materialRequestStatuses'
	) END;
$function$
LANGUAGE sql STABLE;

CREATE OR REPLACE VIEW public.material_requests_list AS
SELECT
	request.id,
	request.date,
	request.construction_site_id,
	request.construction_manager_id,
	request.comment,
	request.version,
	public.construction_sites_ref(site) AS construction_site,
	public.users_ref(manager) AS construction_manager
FROM public.material_requests AS request
LEFT JOIN public.construction_sites AS site ON site.id = request.construction_site_id
LEFT JOIN public.users AS manager ON manager.id = request.construction_manager_id;

CREATE OR REPLACE VIEW public.material_request_items_list AS
SELECT
	item.id,
	item.line_num,
	item.material_request_id,
	item.material_id,
	item.measure_unit_id,
	item.quant,
	item.supplier_id,
	item.required_date,
	item.order_importance_id,
	item.status_id,
	public.materials_ref(material) AS material,
	public.measure_units_ref(measure_unit) AS measure_unit,
	public.suppliers_ref(supplier) AS supplier,
	public.order_importances_ref(importance) AS order_importance,
	public.material_request_statuses_ref(status) AS status
FROM public.material_request_items AS item
LEFT JOIN public.materials AS material ON material.id = item.material_id
LEFT JOIN public.measure_units AS measure_unit ON measure_unit.id = item.measure_unit_id
LEFT JOIN public.suppliers AS supplier ON supplier.id = item.supplier_id
LEFT JOIN public.order_importances AS importance ON importance.id = item.order_importance_id
LEFT JOIN public.material_request_statuses AS status ON status.id = item.status_id;

