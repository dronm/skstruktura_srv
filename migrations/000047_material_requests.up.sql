CREATE TABLE public.order_importances (
	id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
	name text NOT NULL,
	sort_order integer NOT NULL DEFAULT 0,
	is_active boolean NOT NULL DEFAULT true,
	CHECK (btrim(name) <> ''),
	CHECK (sort_order >= 0)
);

COMMENT ON TABLE public.order_importances IS 'Material request importance reference data.';
COMMENT ON COLUMN public.order_importances.name IS 'Display name of the importance level.';
COMMENT ON COLUMN public.order_importances.sort_order IS 'Display and priority order.';
COMMENT ON COLUMN public.order_importances.is_active IS 'Whether the importance level can be selected for new request items.';

CREATE UNIQUE INDEX order_importances_name_idx
	ON public.order_importances USING btree (lower(name));

CREATE INDEX order_importances_sort_order_idx
	ON public.order_importances USING btree (sort_order);

CREATE TABLE public.material_request_statuses (
	id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
	code varchar(40) NOT NULL,
	name text NOT NULL,
	CHECK (btrim(code) <> ''),
	CHECK (btrim(name) <> ''),
	CHECK (code IN ('draft', 'submitted', 'in_progress', 'completed', 'cancelled'))
);

COMMENT ON TABLE public.material_request_statuses IS 'Material request item status reference data.';
COMMENT ON COLUMN public.material_request_statuses.code IS 'Stable status code used by the material request workflow.';
COMMENT ON COLUMN public.material_request_statuses.name IS 'Display name of the status.';

CREATE UNIQUE INDEX material_request_statuses_code_idx
	ON public.material_request_statuses USING btree (code);

CREATE UNIQUE INDEX material_request_statuses_name_idx
	ON public.material_request_statuses USING btree (lower(name));

