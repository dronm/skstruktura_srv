CREATE OR REPLACE FUNCTION public.rg_materials_rebuild()
RETURNS void
LANGUAGE plpgsql
AS $function$
BEGIN
	TRUNCATE TABLE public.rg_materials_period, public.rg_materials_current;

	INSERT INTO public.rg_materials_period (
		period_start,
		construction_site_id,
		material_id,
		quant,
		amount,
		pending_count
	)
	SELECT
		public.register_month_start(action.effective_at),
		action.construction_site_id,
		action.material_id,
		SUM(action.quant)::numeric(19, 4),
		CASE
			WHEN bool_or(action.amount_pending OR action.amount IS NULL) THEN NULL
			ELSE SUM(action.amount)::numeric(19, 4)
		END,
		COUNT(*) FILTER (WHERE action.amount_pending OR action.amount IS NULL)::integer
	FROM public.ra_materials AS action
	GROUP BY
		public.register_month_start(action.effective_at),
		action.construction_site_id,
		action.material_id
	HAVING SUM(action.quant) <> 0
		OR COUNT(*) FILTER (WHERE action.amount_pending OR action.amount IS NULL) > 0
		OR COALESCE(SUM(action.amount), 0) <> 0;

	INSERT INTO public.rg_materials_current (
		construction_site_id,
		material_id,
		quant,
		amount,
		pending_count
	)
	SELECT
		action.construction_site_id,
		action.material_id,
		SUM(action.quant)::numeric(19, 4),
		CASE
			WHEN bool_or(action.amount_pending OR action.amount IS NULL) THEN NULL
			ELSE SUM(action.amount)::numeric(19, 4)
		END,
		COUNT(*) FILTER (WHERE action.amount_pending OR action.amount IS NULL)::integer
	FROM public.ra_materials AS action
	GROUP BY action.construction_site_id, action.material_id
	HAVING SUM(action.quant) <> 0
		OR COUNT(*) FILTER (WHERE action.amount_pending OR action.amount IS NULL) > 0
		OR COALESCE(SUM(action.amount), 0) <> 0;
END;
$function$;

CREATE OR REPLACE FUNCTION public.materials_revalue()
RETURNS integer
LANGUAGE plpgsql
AS $function$
DECLARE
	v_allow_negative boolean;
	v_pass integer := 0;
	v_max_passes integer;
	v_changed integer;
	v_total_pending integer;
	v_row record;
	v_state_quant numeric;
	v_state_amount numeric;
	v_out_quant numeric;
	v_covered numeric;
	v_known_amount numeric;
	v_unit_cost numeric;
	v_in_amount numeric;
	v_remaining_quant numeric;
	v_remaining_amount numeric;
	v_cover_remaining numeric;
	v_alloc_quant numeric;
	v_alloc_amount numeric;
	v_pending record;
BEGIN
	PERFORM set_config('skstruktura.material_valuation_internal', 'on', true);

	SELECT materials_allow_negative_open_period
	INTO v_allow_negative
	FROM public.register_settings
	WHERE id = 1;

	CREATE TEMP TABLE IF NOT EXISTS pg_temp.material_valuation_prev (
		action_id bigint PRIMARY KEY,
		amount numeric(19, 4),
		amount_pending boolean NOT NULL
	) ON COMMIT DROP;
	TRUNCATE pg_temp.material_valuation_prev;

	INSERT INTO pg_temp.material_valuation_prev(action_id, amount, amount_pending)
	SELECT id, amount, amount_pending
	FROM public.ra_materials;

	SELECT GREATEST(COUNT(*) + 1, 2)::integer
	INTO v_max_passes
	FROM public.ra_materials
	WHERE recorder_type = 'MaterialTransfer';

	LOOP
		v_pass := v_pass + 1;

		CREATE TEMP TABLE IF NOT EXISTS pg_temp.material_valuation_state (
			construction_site_id integer NOT NULL,
			material_id integer NOT NULL,
			quant numeric NOT NULL,
			amount numeric,
			PRIMARY KEY (construction_site_id, material_id)
		) ON COMMIT DROP;
		TRUNCATE pg_temp.material_valuation_state;

		CREATE TEMP TABLE IF NOT EXISTS pg_temp.material_valuation_work (
			action_id bigint PRIMARY KEY,
			known_amount numeric NOT NULL DEFAULT 0,
			pending_quant numeric NOT NULL DEFAULT 0,
			is_pending boolean NOT NULL DEFAULT false
		) ON COMMIT DROP;
		TRUNCATE pg_temp.material_valuation_work;

		FOR v_row IN
			SELECT
				action.*,
				CASE
					WHEN action.recorder_type = 'MaterialTransfer' AND action.movement_order = 2 THEN (
						SELECT abs(prev.amount)
						FROM public.ra_materials AS source_action
						LEFT JOIN pg_temp.material_valuation_prev AS prev
							ON prev.action_id = source_action.id
						WHERE source_action.recorder_type = action.recorder_type
							AND source_action.recorder_id = action.recorder_id
							AND source_action.recorder_item_id = action.recorder_item_id
							AND source_action.movement_order = 1
						LIMIT 1
					)
					ELSE action.source_amount
				END AS incoming_amount
			FROM public.ra_materials AS action
			ORDER BY
				action.effective_at,
				CASE action.recorder_type
					WHEN 'MaterialReceipt' THEN 1
					WHEN 'MaterialTransfer' THEN 2
					WHEN 'MaterialConsumption' THEN 3
					ELSE 9
				END,
				action.recorder_id,
				action.recorder_item_id NULLS LAST,
				action.movement_order,
				action.id
		LOOP
			INSERT INTO pg_temp.material_valuation_state(
				construction_site_id,
				material_id,
				quant,
				amount
			)
			VALUES (v_row.construction_site_id, v_row.material_id, 0, 0)
			ON CONFLICT DO NOTHING;

			SELECT quant, amount
			INTO v_state_quant, v_state_amount
			FROM pg_temp.material_valuation_state
			WHERE construction_site_id = v_row.construction_site_id
				AND material_id = v_row.material_id;

			IF v_row.quant > 0 THEN
				v_in_amount := v_row.incoming_amount;

				IF v_in_amount IS NULL THEN
					UPDATE pg_temp.material_valuation_state
					SET quant = quant + v_row.quant,
						amount = NULL
					WHERE construction_site_id = v_row.construction_site_id
						AND material_id = v_row.material_id;

					INSERT INTO pg_temp.material_valuation_work(action_id, is_pending)
					VALUES (v_row.id, true)
					ON CONFLICT (action_id) DO UPDATE SET is_pending = true;
					CONTINUE;
				END IF;

				v_remaining_quant := v_row.quant;
				v_remaining_amount := v_in_amount;
				v_unit_cost := CASE WHEN v_row.quant = 0 THEN 0 ELSE v_in_amount / v_row.quant END;

				IF v_state_quant < 0 THEN
					v_cover_remaining := LEAST(v_remaining_quant, -v_state_quant);
					FOR v_pending IN
						SELECT work.action_id, work.pending_quant, work.known_amount
						FROM pg_temp.material_valuation_work AS work
						JOIN public.ra_materials AS pending_action ON pending_action.id = work.action_id
						WHERE work.pending_quant > 0
							AND pending_action.construction_site_id = v_row.construction_site_id
							AND pending_action.material_id = v_row.material_id
						ORDER BY
							pending_action.effective_at,
							pending_action.id
					LOOP
						EXIT WHEN v_cover_remaining <= 0;
						v_alloc_quant := LEAST(v_cover_remaining, v_pending.pending_quant);
						v_alloc_amount := CASE
							WHEN v_alloc_quant = v_remaining_quant THEN v_remaining_amount
							ELSE round(v_alloc_quant * v_unit_cost, 4)
						END;

						UPDATE pg_temp.material_valuation_work
						SET
							known_amount = known_amount + v_alloc_amount,
							pending_quant = pending_quant - v_alloc_quant,
							is_pending = (pending_quant - v_alloc_quant) > 0
						WHERE action_id = v_pending.action_id;

						v_remaining_quant := v_remaining_quant - v_alloc_quant;
						v_remaining_amount := v_remaining_amount - v_alloc_amount;
						v_cover_remaining := v_cover_remaining - v_alloc_quant;
					END LOOP;
				END IF;

				UPDATE pg_temp.material_valuation_state
				SET
					quant = quant + v_row.quant,
					amount = CASE
						WHEN quant + v_row.quant < 0 THEN NULL
						WHEN amount IS NULL AND quant >= 0 THEN NULL
						WHEN quant < 0 THEN GREATEST(v_remaining_amount, 0)
						ELSE COALESCE(amount, 0) + v_in_amount
					END
				WHERE construction_site_id = v_row.construction_site_id
					AND material_id = v_row.material_id;

				INSERT INTO pg_temp.material_valuation_work(action_id, known_amount, pending_quant, is_pending)
				VALUES (v_row.id, v_in_amount, 0, false)
				ON CONFLICT (action_id) DO UPDATE
				SET known_amount = EXCLUDED.known_amount, pending_quant = 0, is_pending = false;
			ELSE
				v_out_quant := -v_row.quant;
				v_known_amount := 0;

				IF v_state_quant > 0 AND v_state_amount IS NOT NULL THEN
					v_covered := LEAST(v_out_quant, v_state_quant);
					IF v_covered = v_state_quant THEN
						v_known_amount := v_state_amount;
					ELSE
						v_known_amount := round((v_state_amount / v_state_quant) * v_covered, 4);
					END IF;
				ELSE
					v_covered := 0;
				END IF;

				INSERT INTO pg_temp.material_valuation_work(
					action_id,
					known_amount,
					pending_quant,
					is_pending
				)
				VALUES (
					v_row.id,
					v_known_amount,
					v_out_quant - v_covered,
					(v_out_quant - v_covered) > 0
				)
				ON CONFLICT (action_id) DO UPDATE
				SET
					known_amount = EXCLUDED.known_amount,
					pending_quant = EXCLUDED.pending_quant,
					is_pending = EXCLUDED.is_pending;

				UPDATE pg_temp.material_valuation_state
				SET
					quant = quant - v_out_quant,
					amount = CASE
						WHEN v_out_quant > v_covered THEN NULL
						WHEN quant - v_out_quant = 0 THEN 0
						WHEN amount IS NULL THEN NULL
						ELSE amount - v_known_amount
					END
				WHERE construction_site_id = v_row.construction_site_id
					AND material_id = v_row.material_id;

				IF NOT v_allow_negative AND v_state_quant - v_out_quant < 0 THEN
					RAISE EXCEPTION 'Negative material inventory is disabled: site %, material %, action % would produce quantity %',
						v_row.construction_site_id,
						v_row.material_id,
						v_row.id,
						v_state_quant - v_out_quant
						USING ERRCODE = '23514';
				END IF;
			END IF;
		END LOOP;

		UPDATE public.ra_materials AS action
		SET
			amount = CASE
				WHEN action.quant > 0 THEN work.known_amount::numeric(19, 4)
				WHEN work.is_pending THEN NULL
				ELSE (-work.known_amount)::numeric(19, 4)
			END,
			amount_pending = work.is_pending
		FROM pg_temp.material_valuation_work AS work
		WHERE work.action_id = action.id;

		SELECT COUNT(*)::integer
		INTO v_changed
		FROM public.ra_materials AS action
		LEFT JOIN pg_temp.material_valuation_prev AS prev ON prev.action_id = action.id
		WHERE prev.action_id IS NULL
			OR action.amount IS DISTINCT FROM prev.amount
			OR action.amount_pending IS DISTINCT FROM prev.amount_pending;

		TRUNCATE pg_temp.material_valuation_prev;
		INSERT INTO pg_temp.material_valuation_prev(action_id, amount, amount_pending)
		SELECT id, amount, amount_pending
		FROM public.ra_materials;

		EXIT WHEN v_changed = 0 OR v_pass >= v_max_passes;
	END LOOP;

	PERFORM public.rg_materials_rebuild();

	SELECT COUNT(*)::integer
	INTO v_total_pending
	FROM public.ra_materials
	WHERE amount_pending OR amount IS NULL;

	RETURN v_total_pending;
END;
$function$;

COMMENT ON FUNCTION public.materials_revalue() IS
	'Deterministically recalculates weighted-average monetary values for all material movements. Negative open-period shortages remain pending until later valued receipts resolve them; transfer values propagate over repeated passes.';

DROP FUNCTION IF EXISTS public.rg_materials_balance(integer[], integer[]);
CREATE OR REPLACE FUNCTION public.rg_materials_balance(
	in_construction_site_ids integer[] DEFAULT NULL,
	in_material_ids integer[] DEFAULT NULL
)
RETURNS TABLE (
	construction_site_id integer,
	material_id integer,
	quant numeric(19, 4),
	amount numeric(19, 4),
	average_cost numeric(19, 6),
	amount_pending boolean
)
LANGUAGE sql
STABLE
AS $function$
	SELECT
		balance.construction_site_id,
		balance.material_id,
		balance.quant,
		balance.amount,
		CASE
			WHEN balance.amount IS NULL OR balance.quant = 0 THEN NULL
			ELSE (balance.amount / balance.quant)::numeric(19, 6)
		END,
		balance.pending_count > 0
	FROM public.rg_materials_current AS balance
	WHERE (
		in_construction_site_ids IS NULL
		OR cardinality(in_construction_site_ids) = 0
		OR balance.construction_site_id = ANY(in_construction_site_ids)
	)
	AND (
		in_material_ids IS NULL
		OR cardinality(in_material_ids) = 0
		OR balance.material_id = ANY(in_material_ids)
	)
	AND (balance.quant <> 0 OR balance.pending_count > 0 OR COALESCE(balance.amount, 0) <> 0)
	ORDER BY balance.construction_site_id, balance.material_id;
$function$;

DROP FUNCTION IF EXISTS public.rg_materials_balance(timestamptz, integer[], integer[]);
CREATE OR REPLACE FUNCTION public.rg_materials_balance(
	in_effective_at timestamptz,
	in_construction_site_ids integer[] DEFAULT NULL,
	in_material_ids integer[] DEFAULT NULL
)
RETURNS TABLE (
	construction_site_id integer,
	material_id integer,
	quant numeric(19, 4),
	amount numeric(19, 4),
	average_cost numeric(19, 6),
	amount_pending boolean
)
LANGUAGE sql
STABLE
AS $function$
	WITH movements AS (
		SELECT action.*
		FROM public.ra_materials AS action
		WHERE action.effective_at <= in_effective_at
			AND (
				in_construction_site_ids IS NULL
				OR cardinality(in_construction_site_ids) = 0
				OR action.construction_site_id = ANY(in_construction_site_ids)
			)
			AND (
				in_material_ids IS NULL
				OR cardinality(in_material_ids) = 0
				OR action.material_id = ANY(in_material_ids)
			)
	), grouped AS (
		SELECT
			construction_site_id,
			material_id,
			SUM(quant)::numeric(19, 4) AS quant,
			CASE
				WHEN bool_or(amount_pending OR amount IS NULL) THEN NULL
				ELSE SUM(amount)::numeric(19, 4)
			END AS amount,
			bool_or(amount_pending OR amount IS NULL) AS amount_pending
		FROM movements
		GROUP BY construction_site_id, material_id
	)
	SELECT
		grouped.construction_site_id,
		grouped.material_id,
		grouped.quant,
		grouped.amount,
		CASE
			WHEN grouped.amount IS NULL OR grouped.quant = 0 THEN NULL
			ELSE (grouped.amount / grouped.quant)::numeric(19, 6)
		END,
		grouped.amount_pending
	FROM grouped
	WHERE grouped.quant <> 0 OR grouped.amount_pending OR COALESCE(grouped.amount, 0) <> 0
	ORDER BY grouped.construction_site_id, grouped.material_id;
$function$;

CREATE OR REPLACE FUNCTION public.materials_close_period(
	in_closed_through date,
	in_user_id integer DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
AS $function$
DECLARE
	v_current_closed date;
	v_cutoff timestamptz;
	v_pending integer;
	v_negative integer;
	v_closure_id bigint;
BEGIN
	IF in_closed_through IS NULL THEN
		RAISE EXCEPTION 'closed_through is required' USING ERRCODE = '22004';
	END IF;

	SELECT materials_closed_through
	INTO v_current_closed
	FROM public.register_settings
	WHERE id = 1
	FOR UPDATE;

	IF v_current_closed IS NOT NULL AND in_closed_through <= v_current_closed THEN
		RAISE EXCEPTION 'New closing date % must be later than current closing date %', in_closed_through, v_current_closed
			USING ERRCODE = '22023';
	END IF;

	PERFORM public.materials_revalue();

	v_cutoff := ((in_closed_through + 1)::timestamp AT TIME ZONE public.register_business_timezone()) - interval '1 microsecond';

	SELECT COUNT(*)::integer
	INTO v_pending
	FROM public.ra_materials
	WHERE effective_at <= v_cutoff
		AND (amount_pending OR amount IS NULL);

	IF v_pending > 0 THEN
		RAISE EXCEPTION 'Cannot close material accounting through %: % movement(s) still have pending monetary valuation', in_closed_through, v_pending
			USING ERRCODE = '23514';
	END IF;

	WITH ordered AS (
		SELECT
			action.construction_site_id,
			action.material_id,
			action.id,
			SUM(action.quant) OVER (
				PARTITION BY action.construction_site_id, action.material_id
				ORDER BY
					action.effective_at,
					CASE action.recorder_type
						WHEN 'MaterialReceipt' THEN 1
						WHEN 'MaterialTransfer' THEN 2
						WHEN 'MaterialConsumption' THEN 3
						ELSE 9
					END,
					action.recorder_id,
					action.recorder_item_id NULLS LAST,
					action.movement_order,
					action.id
				ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
			) AS running_quant
		FROM public.ra_materials AS action
		WHERE action.effective_at <= v_cutoff
	)
	SELECT COUNT(*)::integer
	INTO v_negative
	FROM ordered
	WHERE running_quant < 0;

	IF v_negative > 0 THEN
		RAISE EXCEPTION 'Cannot close material accounting through %: % material balance(s) are negative', in_closed_through, v_negative
			USING ERRCODE = '23514';
	END IF;

	INSERT INTO public.material_valuation_closures(closed_through, closed_by)
	VALUES (in_closed_through, in_user_id)
	RETURNING id INTO v_closure_id;

	INSERT INTO public.material_valuation_snapshots(
		closure_id,
		construction_site_id,
		material_id,
		quant,
		amount
	)
	SELECT
		v_closure_id,
		balance.construction_site_id,
		balance.material_id,
		balance.quant,
		COALESCE(balance.amount, 0)
	FROM public.rg_materials_balance(v_cutoff, NULL, NULL) AS balance
	WHERE balance.quant <> 0 OR COALESCE(balance.amount, 0) <> 0;

	UPDATE public.register_settings
	SET materials_closed_through = in_closed_through
	WHERE id = 1;

	RETURN v_closure_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.materials_reopen_period(in_user_id integer DEFAULT NULL)
RETURNS bigint
LANGUAGE plpgsql
AS $function$
DECLARE
	v_closure_id bigint;
BEGIN
	SELECT id
	INTO v_closure_id
	FROM public.material_valuation_closures
	WHERE reopened_at IS NULL
	ORDER BY id DESC
	LIMIT 1
	FOR UPDATE;

	IF v_closure_id IS NULL THEN
		UPDATE public.register_settings
		SET materials_closed_through = NULL
		WHERE id = 1;
		RETURN NULL;
	END IF;

	UPDATE public.material_valuation_closures
	SET
		reopened_at = CURRENT_TIMESTAMP,
		reopened_by = in_user_id
	WHERE id = v_closure_id;

	UPDATE public.register_settings
	SET materials_closed_through = NULL
	WHERE id = 1;

	RETURN v_closure_id;
END;
$function$;

DROP VIEW IF EXISTS public.material_balances_list;
CREATE VIEW public.material_balances_list AS
SELECT
	material.id,
	balance.construction_site_id,
	public.construction_sites_ref(site) AS construction_site,
	material.material_type_id,
	public.material_types_ref(material_type) AS material_type,
	material_type.name AS material_type_name,
	balance.material_id,
	public.materials_ref(material) AS material,
	material.name AS material_name,
	material.measure_unit_id,
	public.measure_units_ref(measure_unit) AS measure_unit,
	balance.quant::numeric(19, 4) AS balance,
	balance.amount::numeric(19, 4) AS amount,
	CASE
		WHEN balance.amount IS NULL OR balance.quant = 0 THEN NULL
		ELSE (balance.amount / balance.quant)::numeric(19, 6)
	END AS average_cost,
	balance.pending_count > 0 AS amount_pending
FROM public.rg_materials_current AS balance
JOIN public.construction_sites AS site
	ON site.id = balance.construction_site_id
JOIN public.materials AS material
	ON material.id = balance.material_id
JOIN public.material_types AS material_type
	ON material_type.id = material.material_type_id
JOIN public.measure_units AS measure_unit
	ON measure_unit.id = material.measure_unit_id
WHERE balance.quant <> 0 OR balance.pending_count > 0 OR COALESCE(balance.amount, 0) <> 0;


-- Rebuild the authoritative action ledger from source documents so every
-- pre-existing movement receives recorder-line identity and receipt cost basis.
TRUNCATE TABLE public.ra_materials RESTART IDENTITY;

SELECT public.ra_materials_add_act(
	receipt.date,
	'MaterialReceipt',
	receipt.id,
	item.id,
	1::smallint,
	COALESCE(item.construction_site_id, receipt.construction_site_id),
	item.material_id,
	item.quant,
	CASE
		WHEN settings.materials_exclude_vat_from_cost THEN item.amount - item.vat_amount
		ELSE item.amount
	END
)
FROM public.material_receipts AS receipt
JOIN public.material_receipt_items AS item
	ON item.material_receipt_id = receipt.id
CROSS JOIN public.register_settings AS settings
WHERE settings.id = 1
ORDER BY receipt.date, receipt.id, item.line_num, item.id;

SELECT public.ra_materials_add_act(
	consumption.date,
	'MaterialConsumption',
	consumption.id,
	item.id,
	1::smallint,
	consumption.construction_site_id,
	item.material_id,
	-item.quant,
	NULL
)
FROM public.material_consumptions AS consumption
JOIN public.material_consumption_items AS item
	ON item.material_consumption_id = consumption.id
ORDER BY consumption.date, consumption.id, item.line_num, item.id;

SELECT public.ra_materials_add_act(
	transfer.date,
	'MaterialTransfer',
	transfer.id,
	movement.id,
	movement.movement_order::smallint,
	movement.construction_site_id,
	movement.material_id,
	movement.quant,
	NULL
)
FROM public.material_transfers AS transfer
JOIN LATERAL (
	SELECT
		item.line_num,
		item.id,
		transfer.source_construction_site_id AS construction_site_id,
		item.material_id,
		-item.quant AS quant,
		1 AS movement_order
	FROM public.material_transfer_items AS item
	WHERE item.material_transfer_id = transfer.id

	UNION ALL

	SELECT
		item.line_num,
		item.id,
		transfer.destination_construction_site_id AS construction_site_id,
		item.material_id,
		item.quant AS quant,
		2 AS movement_order
	FROM public.material_transfer_items AS item
	WHERE item.material_transfer_id = transfer.id
) AS movement ON true
ORDER BY transfer.date, transfer.id, movement.line_num, movement.id, movement.movement_order;

SELECT public.materials_revalue();

