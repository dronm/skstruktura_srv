CREATE OR REPLACE FUNCTION public.rg_materials_apply_delta(
	in_effective_at timestamptz,
	in_construction_site_id integer,
	in_material_id integer,
	in_delta_quant numeric(19, 4),
	in_delta_amount numeric(19, 4),
	in_pending_delta integer
)
RETURNS void
LANGUAGE plpgsql
AS $function$
DECLARE
	v_period_start date;
BEGIN
	IF in_delta_quant = 0 AND COALESCE(in_delta_amount, 0) = 0 AND in_pending_delta = 0 THEN
		RETURN;
	END IF;

	v_period_start := public.register_month_start(in_effective_at);

	INSERT INTO public.rg_materials_period (
		period_start,
		construction_site_id,
		material_id,
		quant,
		amount,
		pending_count
	)
	VALUES (
		v_period_start,
		in_construction_site_id,
		in_material_id,
		in_delta_quant,
		CASE WHEN in_pending_delta > 0 THEN NULL ELSE COALESCE(in_delta_amount, 0) END,
		GREATEST(in_pending_delta, 0)
	)
	ON CONFLICT (construction_site_id, material_id, period_start)
	DO UPDATE
	SET
		quant = rg_materials_period.quant + EXCLUDED.quant,
		pending_count = rg_materials_period.pending_count + in_pending_delta,
		amount = CASE
			WHEN rg_materials_period.pending_count + in_pending_delta > 0 THEN NULL
			ELSE COALESCE(rg_materials_period.amount, 0) + COALESCE(in_delta_amount, 0)
		END;

	DELETE FROM public.rg_materials_period
	WHERE period_start = v_period_start
		AND construction_site_id = in_construction_site_id
		AND material_id = in_material_id
		AND quant = 0
		AND pending_count = 0
		AND COALESCE(amount, 0) = 0;

	INSERT INTO public.rg_materials_current (
		construction_site_id,
		material_id,
		quant,
		amount,
		pending_count
	)
	VALUES (
		in_construction_site_id,
		in_material_id,
		in_delta_quant,
		CASE WHEN in_pending_delta > 0 THEN NULL ELSE COALESCE(in_delta_amount, 0) END,
		GREATEST(in_pending_delta, 0)
	)
	ON CONFLICT (construction_site_id, material_id)
	DO UPDATE
	SET
		quant = rg_materials_current.quant + EXCLUDED.quant,
		pending_count = rg_materials_current.pending_count + in_pending_delta,
		amount = CASE
			WHEN rg_materials_current.pending_count + in_pending_delta > 0 THEN NULL
			ELSE COALESCE(rg_materials_current.amount, 0) + COALESCE(in_delta_amount, 0)
		END;

	DELETE FROM public.rg_materials_current
	WHERE construction_site_id = in_construction_site_id
		AND material_id = in_material_id
		AND quant = 0
		AND pending_count = 0
		AND COALESCE(amount, 0) = 0;
END;
$function$;

CREATE OR REPLACE FUNCTION public.ra_materials_process()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
	IF TG_OP = 'INSERT' THEN
		PERFORM public.rg_materials_apply_delta(
			NEW.effective_at,
			NEW.construction_site_id,
			NEW.material_id,
			NEW.quant,
			NEW.amount,
			CASE WHEN NEW.amount_pending THEN 1 ELSE 0 END
		);
		RETURN NEW;
	END IF;

	IF TG_OP = 'DELETE' THEN
		PERFORM public.rg_materials_apply_delta(
			OLD.effective_at,
			OLD.construction_site_id,
			OLD.material_id,
			-OLD.quant,
			CASE WHEN OLD.amount IS NULL THEN NULL ELSE -OLD.amount END,
			CASE WHEN OLD.amount_pending THEN -1 ELSE 0 END
		);
		RETURN OLD;
	END IF;

	RETURN NEW;
END;
$function$;

