CREATE OR REPLACE FUNCTION public.materials_assert_open_date(in_effective_at timestamptz)
RETURNS void
LANGUAGE plpgsql
STABLE
AS $function$
DECLARE
	v_closed_through date;
	v_effective_date date;
BEGIN
	SELECT materials_closed_through
	INTO v_closed_through
	FROM public.register_settings
	WHERE id = 1;

	IF v_closed_through IS NULL THEN
		RETURN;
	END IF;

	v_effective_date := (in_effective_at AT TIME ZONE public.register_business_timezone())::date;
	IF v_effective_date <= v_closed_through THEN
		RAISE EXCEPTION 'Material accounting is closed through %, movement date % is locked',
			v_closed_through,
			v_effective_date
			USING ERRCODE = '55000';
	END IF;
END;
$function$;

